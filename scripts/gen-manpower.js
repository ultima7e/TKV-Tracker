// Generate lib/manpower-data.js from a manpower workbook.
// Manpower is NOT fetched live (unlike the other panels) — the workbook lives in
// scattered daily folders, so we bake the latest sheet straight into the app.
// To refresh: node scripts/gen-manpower.js "<path to Manpower work Details Sheet.xlsx>"
const fs = require('fs');
const path = require('path');
const { workbookToBoth } = require('../lib/workbook');
const { parseManpower } = require('../lib/parsers');

const src = process.argv[2];
if (!src) { console.error('Usage: node scripts/gen-manpower.js "<path to manpower .xlsx>"'); process.exit(1); }

const buf = fs.readFileSync(src);
const mp = parseManpower(workbookToBoth(buf).matrices);
if (!mp.date) { console.error('Could not find a date-named sheet in', src); process.exit(1); }

const snapshot = {
  date: mp.date,
  mobilized: mp.mobilized,
  mobilizedTotal: mp.mobilizedTotal,
  idle: mp.idle,
  idleTotal: mp.idleTotal,
  locations: mp.locations,
};

const out = `// AUTO-GENERATED by scripts/gen-manpower.js — do not edit by hand.
// Source workbook: ${path.basename(src)}
// Manpower is baked in (not fetched live). To refresh, re-run:
//   node scripts/gen-manpower.js "<path to the latest manpower .xlsx>"
module.exports = ${JSON.stringify(snapshot, null, 2)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'lib', 'manpower-data.js'), out);
console.log('Wrote lib/manpower-data.js  ·  date', snapshot.date,
  '· on-site', (snapshot.locations || []).reduce((a, l) => a + l.total, 0),
  '· mobilized', snapshot.mobilizedTotal.total, '· idle', snapshot.idleTotal.total,
  '· locations', (snapshot.locations || []).length);
